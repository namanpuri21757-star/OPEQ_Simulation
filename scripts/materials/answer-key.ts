/** Builds docs/materials/answer-key.md and the version printed in the terminal. */

import { COUNTRY_LETTERS, COUNTRY_NAMES } from '../../src/shared/constants.js';
import type { PresetName, Settings } from '../../src/shared/settings.js';
import { PRESET_NAMES, PRESETS, economicUnits } from '../../src/shared/settings.js';
import {
  bestResponseRawTenths,
  bestResponseTenths,
  competitiveOutcome,
  cooperativeMax,
  newProducerTenths,
} from '../../src/shared/engine/engine.js';
import { formatPrice, formatProfitK, formatQuantity } from '../../src/shared/units.js';
import { newProducerYear, scenariosForYear } from './scenarios.js';

export const GENERATED_NOTE =
  '<!-- Generated by `npm run benchmarks`. Do not edit by hand: every number comes from the engine. -->';

/** The answer key for one preset, as Markdown lines. */
export function answerKeyFor(name: PresetName): string[] {
  const settings = PRESETS[name];
  const lines: string[] = [];
  lines.push(`## ${name}`, '');
  lines.push(...settingsLines(settings));
  lines.push('', ...benchmarkLines(settings, 1));
  lines.push('', ...scenarioTable(settings, 1, 'Year 1 (no new producer)'));

  const npYear = newProducerYear(settings);
  if (npYear !== null) {
    const qn = formatQuantity(newProducerTenths(npYear, settings));
    lines.push(
      '',
      ...scenarioTable(
        settings,
        npYear,
        `Year ${npYear} (a new producer adds ${qn} million barrels)`,
      ),
    );
  }

  lines.push('', ...bestResponseTable(settings, 1));
  return lines;
}

/** The whole file. */
export function answerKeyDocument(): string {
  const lines: string[] = [
    '# Teacher answer key',
    '',
    GENERATED_NOTE,
    '',
    'Benchmarks for every preset. These are for your eyes and the debrief only:',
    'SPEC section 3 says students never see best responses during play.',
    '',
    'Quantities are millions of barrels a year. Prices are dollars per barrel.',
    'Profits are millions of dollars for one year.',
    '',
  ];
  PRESET_NAMES.forEach((name, index) => {
    if (index > 0) lines.push('');
    lines.push(...answerKeyFor(name));
  });
  return `${lines.join('\n')}\n`;
}

function settingsLines(settings: Settings): string[] {
  const u = economicUnits(settings);
  const np = settings.newProducer;
  return [
    `- Price rule: P = max(0, ${settings.a} - ${settings.b} x total supply), cost ${formatPrice(u.costCents)} a barrel.`,
    `- Capacity ${formatQuantity(u.capacityTenths)} each, ${settings.years} scored years plus a practice year.`,
    `- New producer: ${np.enabled ? `Year ${np.year}, ${formatQuantity(newProducerTenths(np.year, settings))} million barrels, ${np.announced ? 'announced' : 'not announced'}` : 'off'}.`,
    `- Production variance: ${settings.variancePct === 0 ? 'off' : `${settings.variancePct}%`}. Disclosure: ${settings.disclosure}.`,
  ];
}

function benchmarkLines(settings: Settings, year: number): string[] {
  const coop = cooperativeMax(settings, year);
  const nash = competitiveOutcome(settings, year);
  return [
    '### The two benchmarks',
    '',
    '| Benchmark | Total supply | Price | Profit for the three together |',
    '| --- | --- | --- | --- |',
    `| Cooperative maximum | ${formatQuantity(coop.totalTenths)} | ${formatPrice(coop.priceCents)} | ${formatProfitK(coop.jointMaxK)} |`,
    `| Competitive (Nash) outcome | ${formatQuantity(nash.totalTenths)} | ${formatPrice(nash.priceCents)} | ${formatProfitK(nash.jointProfitK)} |`,
    '',
    `An equal cooperative share is ${formatQuantity(coop.shareTenths)} each, which three countries can actually produce: total ${formatQuantity(coop.equalShares.totalTenths)}, price ${formatPrice(coop.equalShares.priceCents)}, ${formatProfitK(coop.equalShares.eachProfitK)} each.`,
    `At the competitive outcome each country produces ${formatQuantity(nash.eachTenths)} and earns ${formatProfitK(nash.eachProfitK)}.`,
  ];
}

function scenarioTable(settings: Settings, year: number, title: string): string[] {
  const header = COUNTRY_LETTERS.map((l) => `${COUNTRY_NAMES[l]} (${l})`);
  const lines = [
    `### ${title}`,
    '',
    `| Scenario | ${header.map((h) => `${h} output`).join(' | ')} | Total | Price | ${header.map((h) => `${h} profit`).join(' | ')} | All three |`,
    `| --- | ${COUNTRY_LETTERS.map(() => '---').join(' | ')} | --- | --- | ${COUNTRY_LETTERS.map(() => '---').join(' | ')} | --- |`,
  ];

  for (const row of scenariosForYear(settings, year)) {
    const o = row.outcome;
    const outputs = COUNTRY_LETTERS.map((l) => formatQuantity(o.countries[l].actualTenths));
    const profits = COUNTRY_LETTERS.map((l) => formatProfitK(o.countries[l].profitK));
    const joint = COUNTRY_LETTERS.reduce((sum, l) => sum + o.countries[l].profitK, 0);
    lines.push(
      `| ${row.name} | ${outputs.join(' | ')} | ${formatQuantity(o.totalTenths)} | ${formatPrice(o.priceCents)} | ${profits.join(' | ')} | ${formatProfitK(joint)} |`,
    );
  }

  lines.push('', ...scenariosForYear(settings, year).map((row) => `- ${row.name}: ${row.note}`));
  return lines;
}

function bestResponseTable(settings: Settings, year: number): string[] {
  const { capacityTenths } = economicUnits(settings);
  const coop = cooperativeMax(settings, year);
  const nash = competitiveOutcome(settings, year);
  const totals = [0, coop.shareTenths * 2, nash.eachTenths * 2, capacityTenths * 2];

  const lines = [
    '### Best response (debrief only)',
    '',
    '| If the other two produce | Your best output | Capped by capacity |',
    '| --- | --- | --- |',
  ];
  for (const others of [...new Set(totals)].sort((x, y) => x - y)) {
    const raw = bestResponseRawTenths(others, settings);
    const capped = bestResponseTenths(others, settings);
    lines.push(
      `| ${formatQuantity(others)} | ${formatQuantity(capped)} | ${raw === capped ? 'no' : `yes, the formula asks for ${formatQuantity(raw)}`} |`,
    );
  }
  return lines;
}
